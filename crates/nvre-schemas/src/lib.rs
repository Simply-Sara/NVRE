//! NVRE's record and NIF schemas, embedded in the binary.
//!
//! A release build is meant to be one file the user copies somewhere and
//! runs. The schemas cannot stay on disk beside it, because the editor has
//! to know where a game's layouts live and a copied executable has no
//! repository beside it any more.
//!
//! So the schemas are compiled in. This crate's build script walks the
//! repository's `schemas` directory and writes a table of every layer and
//! every file in it; the editor reads a game's chain out of that table
//! instead of off the disk.
//!
//! The table is the same data the disk holds, in the same order, so a schema
//! read from the binary and a schema read from the directory are the same
//! schema. Nothing here parses JSON: each crate that owns a schema language
//! merges the files itself, so this stays a table of bytes.

use std::sync::OnceLock;

/// One layer of the schema chain: a directory's files, under its name.
///
/// A layer is a directory the schema language merges over the one below it.
/// The name is the directory's path under the repository's `schemas`
/// directory, with `/` between the parts: `base`, `fnv`, `nif/skyrim`.
pub struct Layer {
    /// The layer's name, as the path under `schemas/`.
    pub name: &'static str,
    /// The layer's files, sorted by name, as (name, contents).
    pub files: &'static [(&'static str, &'static str)],
}

/// Every layer, generated by the build script.
pub static LAYERS: &[Layer] = include!(concat!(env!("OUT_DIR"), "/layers.rs"));

/// The layer with this name, if there is one.
///
/// A layer that is not there is not a layer: the base holds what every game
/// shares, and a game with no layer of its own reads the base alone.
pub fn layer(name: &str) -> Option<&'static Layer> {
    LAYERS.iter().find(|l| l.name == name)
}

/// The layer with this name, or the base.
///
/// Used where a missing layer means "no differences of its own", which is
/// how the editor treats a game whose layouts have not been written yet.
pub fn layer_or_base(name: &str) -> &'static Layer {
    layer(name).unwrap_or_else(|| base())
}

/// The base layer: what every game shares.
pub fn base() -> &'static Layer {
    static BASE: OnceLock<&'static Layer> = OnceLock::new();
    BASE.get_or_init(|| layer("base").expect("the base schema layer is always embedded"))
}
