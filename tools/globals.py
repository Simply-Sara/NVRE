#!/usr/bin/env python3
"""Harvest every `... global` function declaration from the shipped `.psc`.

A **bare** call — `StopInstance(x)`, not `Sound.StopInstance(x)` — resolves to a
`global` function, and the compiler writes `callstatic <class> <fn>` for it.
`signatures.rs`'s `IMPORTED` table covers the four classes that are in scope in
every script (`game`, `utility`, `math`, `debug`); this harvests all of them,
which is how `CWScript.log` (255 calls) and `Sound.StopInstance` (62) are found.

Measured over Skyrim SE's `Scripts.zip`: 202 declarations across 15 classes and
**no name declared `global` on more than one class**, so the class is a function
of the name alone.

The declaration's `global` keyword comes *after* the parameter list and often
after `native` — `Function StopInstance(int ai) native global` — so a regex that
looks for the word immediately after `)` misses every native one, which is how a
first attempt found zero globals in `Sound.psc` while the corpus calls it 67
times.

This writes `crates/nvre-papyrus/src/globals.rs`.

Usage:
    python3 tools/globals.py "<Data>/Scripts.zip" \
        > crates/nvre-papyrus/src/globals.rs
"""

import re
import sys
import zipfile
from collections import defaultdict

# `^[ \t]*` and not `\s`: with `\s` the optional return-type prefix reaches
# across a line and takes the previous declaration's `endFunction` as this one's
# return type. The parameter group keeps `re.S` so a signature may wrap.
SIG = re.compile(
    r"^[ \t]*(?:[A-Za-z_][\w\[\]]*[ \t]+)?(?:Function|Event)[ \t]+(\w+)[ \t]*\((.*?)\)([^\n]*)",
    re.I | re.M | re.S,
)
NAME = re.compile(r"^[ \t]*ScriptName[ \t]+(\w+)", re.I | re.M)


def main():
    z = zipfile.ZipFile(sys.argv[1])
    table = defaultdict(set)
    for name in z.namelist():
        if not name.lower().endswith(".psc"):
            continue
        src = z.read(name).decode("cp1252", "replace")
        m = NAME.search(src)
        if not m:
            continue
        cls = m.group(1).lower()
        for g in SIG.finditer(src):
            # The keyword is after the parameter list, and `native` usually
            # precedes it: `...) native global`.
            if re.search(r"\bglobal\b", g.group(3), re.I):
                table[cls].add(g.group(1).lower())

    # A name on two classes would make the answer a guess; report instead of
    # picking one.
    fn2cls = defaultdict(set)
    for c, fns in table.items():
        for f in fns:
            fn2cls[f].add(c)
    clash = {f: cs for f, cs in fn2cls.items() if len(cs) > 1}
    if clash:
        print("// WARNING: ambiguous globals, dropped:", file=sys.stderr)
        for f, cs in sorted(clash.items()):
            print(f"//   {f}: {sorted(cs)}", file=sys.stderr)

    rows = sorted(
        (f, sorted(cs)[0]) for f, cs in fn2cls.items() if len(cs) == 1
    )
    print(
        f"// {len(rows)} global functions over "
        f"{len(table)} classes, {len(clash)} ambiguous",
        file=sys.stderr,
    )

    print("//! Which functions a **bare** call can reach.")
    print("//!")
    print("//! Generated by `tools/globals.py` from the Creation Kit's own")
    print("//! `Scripts.zip`. Do not edit by hand.")
    print("//!")
    print("//! A bare `f(...)` is not necessarily a method on `self`. If `f` is")
    print("//! declared `global` on a class, the compiler writes")
    print("//! `callstatic <class> f`, and emitting `callmethod f self` instead is")
    print("//! accepted by the loader and fails at run time, because `self` has no")
    print("//! such member.")
    print("//!")
    print("//! The class operand is interned **lowercase**; the string table keeps")
    print("//! the first spelling it saw, so a script whose own name is `CWScript`")
    print("//! gets `callstatic CWScript log` and every other file gets")
    print("//! `callstatic dunyngolglowattracttrig DirectMotesAt` — measured, both")
    print("//! occur in the same corpus for two different callers.")
    print()
    print("/// `(function lowercase, class lowercase)` for every `global`")
    print("/// declaration in the shipped corpus.")
    print("///")
    print("/// No name appears twice: over 14,301 sources, no function is `global`")
    print("/// on more than one class, so the class is a function of the name.")
    print("pub const GLOBALS: &[(&str, &str)] = &[")
    for f, c in rows:
        print(f'    ("{f}", "{c}"),')
    print("];")
    print()
    print("/// The class a bare call to `function` must be emitted as a")
    print("/// `callstatic` on, or `None` when no class declares it `global`.")
    print("pub fn global_class(function: &str) -> Option<&'static str> {")
    print("    let n = function.to_ascii_lowercase();")
    print("    GLOBALS.iter().find(|(f, _)| *f == n).map(|(_, c)| *c)")
    print("}")
    print()
    classes = sorted({c for _f, c in rows})
    print("/// Every class that declares at least one `global` function.")
    print("///")
    print("/// A dotted call on one of these — `Sound.StopInstance(x)` — is a")
    print("/// `callstatic`, not a `callmethod` on a variable called `sound`. The")
    print("/// caller must still check that the name is not a property or local of")
    print("/// its own: `Sound Property sfx auto` makes `sfx.Play(...)` a call on the")
    print("/// instance.")
    print("pub const GLOBAL_CLASSES: &[&str] = &[")
    for c in classes:
        print(f'    "{c}",')
    print("];")
    print()
    print("/// Whether `class` declares any `global` function.")
    print("pub fn is_global_class(class: &str) -> bool {")
    print("    let n = class.to_ascii_lowercase();")
    print("    GLOBAL_CLASSES.iter().any(|c| *c == n)")
    print("}")


if __name__ == "__main__":
    main()
