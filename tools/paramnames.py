#!/usr/bin/env python3
"""Harvest parameter NAMES per function, for named-argument calls.

A named argument goes to its parameter's **declared position**, not to the
position it appears in:

    Game.DisablePlayerControls(abMovement = false, abMenu = false,
                               abActivate = false, abFighting = true)

writes all nine parameters of

    Function DisablePlayerControls(bool abMovement = true, bool abFighting = true,
        bool abCamSwitch = false, bool abLooking = false, bool abSneaking = false,
        bool abMenu = true, bool abActivate = true, bool abJournalTabs = false,
        int aiDisablePOVType = 0) native global

with the four named values at slots 0, 5, 6 and 1 and the rest at their
defaults. Passing positionally puts `false` in `abMovement` and `false` in
`abFighting`, which is a call that runs with the wrong booleans.

Measured over Skyrim SE's `Scripts.zip`: 384 such call sites across 176 of the
14,301 shipped sources.

**This is a separate module on purpose.** `tools/params.py` generates
`signatures.rs`, but that file also holds `AUTO_PROPS` and `IMPORTED`, which
params.py does **not** emit — running it would delete both tables and break the
build. So the names live in their own file and their own generator.

Usage:
    python3 tools/paramnames.py "<Data>/Scripts.zip" \
        > crates/nvre-papyrus/src/paramnames.rs
"""

import re
import sys
import zipfile
from collections import Counter, defaultdict

CALL = re.compile(
    r"^[ \t]*(?:[A-Za-z_][\w\[\]]*[ \t]+)?(?:Function|Event)[ \t]+(\w+)[ \t]*\((.*?)\)",
    re.I | re.M | re.S,
)
NAME = re.compile(r"^[ \t]*ScriptName[ \t]+(\w+)", re.I | re.M)


def split_params(text):
    """Split on commas that are not inside brackets or quotes."""
    out, cur, depth, quote = [], [], 0, False
    for ch in text:
        if ch == '"':
            quote = not quote
        elif not quote:
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif ch == "," and depth == 0:
                out.append("".join(cur))
                cur = []
                continue
        cur.append(ch)
    if cur:
        out.append("".join(cur))
    return [p for p in out if p.strip()]


def param_name(spec):
    """`bool abMovement = true` -> `abmovement`; `None` when unreadable."""
    head = re.split(r"\s*=", spec.strip())[0].strip()
    bits = head.split()
    if len(bits) < 2:
        return None
    name = bits[-1]
    if not re.match(r"^[A-Za-z_]\w*$", name):
        return None
    return name.lower()


def main():
    z = zipfile.ZipFile(sys.argv[1])
    by_fn = defaultdict(Counter)
    by_class_fn = defaultdict(Counter)

    for entry in z.namelist():
        if not entry.lower().endswith(".psc"):
            continue
        src = z.read(entry).decode("cp1252", "replace")
        m = NAME.search(src)
        cls = m.group(1).lower() if m else None
        for call in CALL.finditer(src):
            # A parameter list wrapped with a trailing backslash: the backslash
            # is not part of it, and leaving it in makes the next line's first
            # parameter unreadable.
            text = call.group(2).replace("\\", " ")
            names = [param_name(p) for p in split_params(text)]
            if any(n is None for n in names):
                continue
            key = tuple(names)
            by_fn[call.group(1).lower()][key] += 1
            if cls:
                by_class_fn[(cls, call.group(1).lower())][key] += 1

    rows = []
    for fn, c in sorted(by_fn.items()):
        if len(c) == 1:
            names = c.most_common(1)[0][0]
            if names:
                rows.append((fn, names))
    for (cls, fn), c in sorted(by_class_fn.items()):
        if len(c) == 1:
            names = c.most_common(1)[0][0]
            if names:
                rows.append((f"{cls}.{fn}", names))

    print(f"// {len(rows)} entries", file=sys.stderr)

    print("//! Parameter names per function, so a named argument lands in the")
    print("//! right slot.")
    print("//!")
    print("//! Generated by `tools/paramnames.py` from the Creation Kit's own")
    print("//! `Scripts.zip`. Do not edit by hand.")
    print("//!")
    print("//! `Game.DisablePlayerControls(abMovement = false, abMenu = false,")
    print("//! abActivate = false, abFighting = true)` writes **all nine** parameters:")
    print("//! the four named values at their declared slots and the other five at")
    print("//! their defaults. Placing them positionally puts `false` where")
    print("//! `abMovement` and `abFighting` belong, which is a call that runs with")
    print("//! the wrong booleans rather than one that differs in numbering.")
    print("//!")
    print("//! A name is kept only when every declaration that reaches it agrees, on")
    print("//! the same rule the type and default tables use: a name declared two")
    print("//! different ways cannot settle a position.")
    print()
    print("/// `(function or class.function, parameter names)`, lowercased.")
    print("pub const PARAM_NAMES: &[(&str, &[&str])] = &[")
    for key, names in rows:
        listed = ", ".join(f'"{n}"' for n in names)
        print(f'    ("{key}", &[{listed}]),')
    print("];")
    print()
    print("/// The parameter names of `function`, unqualified first and")
    print("/// `class.function` second.")
    print("pub fn param_names(class: &str, function: &str) -> Option<&'static [&'static str]> {")
    print("    let f = function.to_ascii_lowercase();")
    print("    let qualified = format!(\"{}.{}\", class.to_ascii_lowercase(), f);")
    print("    PARAM_NAMES")
    print("        .iter()")
    print("        .find(|(k, _)| *k == qualified)")
    print("        .or_else(|| PARAM_NAMES.iter().find(|(k, _)| *k == f))")
    print("        .map(|(_, v)| *v)")
    print("}")


if __name__ == "__main__":
    main()
